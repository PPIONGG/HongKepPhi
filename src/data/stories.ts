export function getStoryBySlug(slug: string) {
  return stories.find((story) => story.slug === slug);
}

/** เรื่องแรกที่ลงอยู่ท้ายอาร์เรย์ ไล่ฟังจากเก่าไปใหม่ */
export function getPostedQueue() {
  return [...stories].toReversed();
}

export function getFirstPostedStory() {
  return stories[stories.length - 1];
}

export function getPostedNeighbors(slug: string) {
  const queue = getPostedQueue();
  const index = queue.findIndex((story) => story.slug === slug);
  if (index < 0) {
    return { prev: undefined, next: undefined, position: 0, total: queue.length };
  }
  return {
    prev: queue[index - 1],
    next: queue[index + 1],
    position: index + 1,
    total: queue.length,
  };
}

export function getRelatedStories(slug: string, limit = 3) {
  const current = getStoryBySlug(slug);
  if (!current) return [];
  const sameRoom = stories.filter(
    (story) => story.slug !== slug && story.category === current.category,
  );
  if (sameRoom.length >= limit) return sameRoom.slice(0, limit);
  const extras = stories.filter(
    (story) =>
      story.slug !== slug &&
      !sameRoom.some((item) => item.slug === story.slug),
  );
  return [...sameRoom, ...extras].slice(0, limit);
}
